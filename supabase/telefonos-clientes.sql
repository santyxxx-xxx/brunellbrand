drop table if exists _fichas;
create temp table _fichas as
with emparejado as (
  select t.*,
         (select min(h.cliente_nombre) from public.ventas_historicas h
           where public.clave_cliente(h.contacto_original) like public.clave_cliente(t.prefijo) || '%') as cliente_compras
  from _tel t
),
con_nombre as (
  select e.*,
         coalesce(e.cliente_compras, e.nombre_base) as nombre,
         case when e.cliente_compras is null then 'Contacto en Treinta: ' || e.contacto end as nota_contacto
  from emparejado e
)
-- Un cliente con varios contactos: el primer número va al teléfono y los demás a las notas
select public.clave_cliente(nombre) as clave,
       min(nombre) as nombre,
       (array_agg(telefono order by (cliente_compras is null), contacto))[1] as telefono,
       nullif(concat_ws(E'\n',
         string_agg(distinct nota_contacto, E'\n'),
         string_agg(distinct nota, E'\n'),
         case when count(distinct telefono) > 1 then 'Otros números: ' ||
           array_to_string(array_remove(array_agg(distinct telefono), (array_agg(telefono order by (cliente_compras is null), contacto))[1]), ', ') end), '') as notas,
       bool_or(cliente_compras is not null) as con_compras
from con_nombre
group by 1;

insert into public.clientes (clave, nombre, telefono, notas)
select '-', nombre, telefono, notas from _fichas
on conflict (clave) do update set
  telefono = coalesce(public.clientes.telefono, excluded.telefono),
  notas = case
            when excluded.notas is null or coalesce(public.clientes.notas, '') like '%' || excluded.notas || '%'
              then public.clientes.notas
            else concat_ws(E'\n', public.clientes.notas, excluded.notas)
          end;

